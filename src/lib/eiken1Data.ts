// EIKEN1_UNIT1_ENTRIES から WordItem と SentenceItem を動的に生成（同じ品詞の英検1級単語からリアルなダミー選択肢を自動構成）
export const EIKEN1_WORDS: (WordItem & { track: number; num: string })[] =
  EIKEN1_UNIT1_ENTRIES.map((entry, idx) => {
    // 同じ品詞（または全体）からダミー選択肢を3つ選ぶ
    const samePos = EIKEN1_UNIT1_ENTRIES.filter(
      (e) => e.num !== entry.num && e.partOfSpeech === entry.partOfSpeech
    );
    const pool = samePos.length >= 3 ? samePos : EIKEN1_UNIT1_ENTRIES.filter((e) => e.num !== entry.num);

    const d1 = pool[(idx * 3 + 1) % pool.length];
    const d2 = pool[(idx * 3 + 5) % pool.length];
    const d3 = pool[(idx * 3 + 9) % pool.length];

    return {
      id: `eiken1_${entry.num}`,
      num: entry.num,
      track: entry.track,
      english: entry.english,
      japanese: entry.japanese,
      phonetic: entry.phonetic,
      partOfSpeech: `英検1級 #${entry.num} (${entry.partOfSpeech})`,
      grade: "英検1級",
      distractorsJa: [d1.japanese, d2.japanese, d3.japanese],
      distractorsEn: [d1.english, d2.english, d3.english],
      tip: entry.tip,
      exampleSentenceEn: entry.sentenceEn.join(" "),
      exampleSentenceJa: entry.sentenceJa,
    };
  });

export const EIKEN1_SENTENCES: (SentenceItem & { track: number; num: string })[] =
  EIKEN1_UNIT1_ENTRIES.map((entry, idx) => {
    const other1 = EIKEN1_UNIT1_ENTRIES[(idx + 4) % EIKEN1_UNIT1_ENTRIES.length].english;
    const other2 = EIKEN1_UNIT1_ENTRIES[(idx + 11) % EIKEN1_UNIT1_ENTRIES.length].english;

    return {
      id: `eiken1_s_${entry.num}`,
      num: entry.num,
      track: entry.track,
      englishTokens: entry.sentenceEn,
      distractorTokens: [other1, other2],
      japanese: entry.sentenceJa,
      targetWordIds: [`eiken1_${entry.num}`],
      grade: "英検1級",
      grammarPoint: `【英検1級 #${entry.num}】${entry.english} ＝ ${entry.japanese}`,
    };
  });
